    <script type="module">
        app.component('v-sidebar-collapse', {
            template: '#v-sidebar-collapse-template',

            data() {
                return {
                    isCollapsed: {{ request()->cookie('sidebar_collapsed') ? 1 : 0 }},
                }
            },

            mounted() {
                this.syncFromDom();
                window.addEventListener('sidebar-toggled', (e) => {
                    this.isCollapsed = e.detail.isCollapsed ? 1 : 0;
                });
            },

            methods: {
                toggle() {
                    this.isCollapsed = this.isCollapsed ? 0 : 1;

                    var expiryDate = new Date();
                    expiryDate.setMonth(expiryDate.getMonth() + 1);
                    document.cookie = 'sidebar_collapsed=' + this.isCollapsed + '; path=/; expires=' + expiryDate.toGMTString();

                    this.syncAppClass();

                    window.dispatchEvent(new CustomEvent('sidebar-toggled', {
                        detail: { isCollapsed: this.isCollapsed }
                    }));
                },

                syncAppClass() {
                    const app = document.getElementById('app');
                    if (app) {
                        if (this.isCollapsed) {
                            app.classList.add('sidebar-collapsed');
                            app.classList.remove('sidebar-not-collapsed');
                        } else {
                            app.classList.remove('sidebar-collapsed');
                            app.classList.add('sidebar-not-collapsed');
                        }
                    }
                },

                syncFromDom() {
                    const app = document.getElementById('app');
                    if (app) {
                        this.isCollapsed = app.classList.contains('sidebar-collapsed') ? 1 : 0;
                    } else {
                        const cookieVal = this.isCollapsedCookie();
                        this.isCollapsed = parseInt(cookieVal) === 1 ? 1 : 0;
                    }
                },

                isCollapsedCookie() {
                    const cookies = document.cookie.split(';');

                    for (const cookie of cookies) {
                        const [name, value] = cookie.trim().split('=');

                        if (name === 'sidebar_collapsed') {
                            return parseInt(value) || 0;
                        }
                    }

                    return 0;
                },
            },
        });
    </script>
@endPushOnce